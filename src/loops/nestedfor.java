package loops;

public class nestedfor {
    /**
     * <h1>The nested foe loop</h1>
     * @author Ananay
     * @param args
     * @since 2023-02-12
     */
    public static void main(String[] args) {
        for(int i =0;i<3;i++){
            for(int j=0;j<2;j++){
                System.out.println(i);
            }
            System.out.println();
        }
    }
}
