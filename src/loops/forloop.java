package loops;
//For loop is also known as entry control loop because condition is first checked and then executed
public class forloop {
    /**
     * <h1>The for loop</h1>
     * @author Ananay
     * @param args
     * @since 2023-02-12
     */
    public static void main(String[] args) {
        for(int i =0;i<=10;i++){//Initialization //condition //Increment and decrement
            System.out.println(i);
        }
    }
}
