package loops;
//Do while loop is also known as exit control loop
public class dowhile {
    /**
     * <h1>The do while loop</h1>
     * @author Ananay
     * @param args
     * @since 2023-02-12
     */
    public static void main(String[] args) {
        int i=0;
        do{
            System.out.println(i);
            i++;
        }
        while(i<=10);
//        System.out.println("Ananay");
    }
}
