public class incrementanddecrement {
    public static void main(String[] args) {
        // Increment and decrement operators
        int i = 56;
        System.out.println(i++);    // first i is used as 56 and then it is incremented to 57
        int j =64;
        int c = ++j;   //first j is incremented and then the value of c is assigned as j
        System.out.println(i);
        System.out.println(++i);
        System.out.println(i);
    }
}
