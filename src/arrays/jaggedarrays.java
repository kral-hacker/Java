package arrays;

public class jaggedarrays {
    public static void main(String[] args) {
        int [][] jaggedarr = new int [2][]; //This is a jagged array in which we konw the number of rows but not columns.
        //First rows has three columns
        jaggedarr[0] = new int[3];
        //Second row has 2 columns
        jaggedarr[1] = new int[2];
     }
}
