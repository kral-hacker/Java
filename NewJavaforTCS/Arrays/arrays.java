package Arrays;

public class arrays {
    public static void main(){
        // Defining an array
        String[] arr; // square brackets will always come with the defining data type
        // Defining an array with the values
        String cars[] = {"BMW", "MERC", "AUDI", "PORSCHE", "MASERATI"};
        // Accessing the elements
        System.out.println(cars[0]);
        // Change an element
        cars[0] = "KIA";
        System.out.println(cars[0]);
        // length of an array
        System.out.println(cars.length);


        /*
        In c++ there are arrays
        string cars[] = {"BMW", "MERC", "AUDI", "PORSCHE", "MASERATI"};
        notice how in c++ the square brackets come with the variable name
         */

    }
}
